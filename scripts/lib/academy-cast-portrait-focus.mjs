import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const MANIFEST_CONSTANT = 'ACADEMY_CAST_STANDARDIZATION_MANIFEST';
const OUTPUT_FILE = 'src/academy/domain/cast-portrait-focus.generated.ts';
const BASELINE_CAST_ID = 'rie';
const BASELINE_PRESENTATION_SCALE = 1.2;
const ALPHA_THRESHOLD = 16;
const UPPER_BODY_FRACTION = 0.46;

export async function refreshAcademyCastPortraitFocus(repoRoot, manifest = undefined) {
    const slots = manifest ?? readJsonConstant(
        fs.readFileSync(path.join(repoRoot, 'src/academy/domain/cast-standardization-manifest.ts'), 'utf8'),
        MANIFEST_CONSTANT,
    );
    const neutralByCast = new Map();
    for (const slot of slots) {
        if (slot.expression === 'neutral' && !neutralByCast.has(slot.castId)) {
            neutralByCast.set(slot.castId, slot);
        }
    }

    const baselineSlot = neutralByCast.get(BASELINE_CAST_ID);
    if (!baselineSlot) throw new Error(`Portrait-focus baseline ${BASELINE_CAST_ID} has no neutral sprite.`);
    const baseline = await measureUpperBody(repoRoot, baselineSlot.assetPath);
    const focusByCast = new Map();

    for (const [castId, slot] of neutralByCast) {
        const measurement = await measureUpperBody(repoRoot, slot.assetPath);
        const scale = clamp(
            (baseline.relativeUpperWidth / measurement.relativeUpperWidth) * BASELINE_PRESENTATION_SCALE,
            1,
            2.2,
        );
        const translateYPercent = clamp(
            (baseline.relativeTop - (measurement.relativeTop * scale)) * 100,
            -12,
            2,
        );
        focusByCast.set(castId, {
            scale: round(scale),
            translateYPercent: round(translateYPercent),
        });
    }

    const focusByPath = Object.fromEntries(
        slots
            .map(slot => [slot.assetPath, focusByCast.get(slot.castId) ?? { scale: 1, translateYPercent: 0 }])
            .sort(([left], [right]) => left.localeCompare(right)),
    );
    const output = `// Generated by scripts/academy-cast-portrait-focus.mjs. Do not edit by hand.\n`
        + `export interface AcademyCastPortraitFocus {\n`
        + `    readonly scale: number;\n`
        + `    readonly translateYPercent: number;\n`
        + `}\n\n`
        + `export const ACADEMY_CAST_PORTRAIT_FOCUS_BY_PATH = ${JSON.stringify(focusByPath)} as const satisfies Readonly<Record<string, AcademyCastPortraitFocus>>;\n`;
    fs.writeFileSync(path.join(repoRoot, OUTPUT_FILE), output);
    return { castCount: focusByCast.size, assetCount: Object.keys(focusByPath).length };
}

async function measureUpperBody(repoRoot, assetPath) {
    const file = path.join(repoRoot, 'public', assetPath.slice(1));
    const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const alphaIndex = info.channels - 1;
    let minX = info.width;
    let minY = info.height;
    let maxX = -1;
    let maxY = -1;

    for (let y = 0; y < info.height; y += 1) {
        for (let x = 0; x < info.width; x += 1) {
            const alpha = data[((y * info.width) + x) * info.channels + alphaIndex];
            if (alpha <= ALPHA_THRESHOLD) continue;
            minX = Math.min(minX, x);
            minY = Math.min(minY, y);
            maxX = Math.max(maxX, x);
            maxY = Math.max(maxY, y);
        }
    }
    if (maxX < minX || maxY < minY) throw new Error(`Sprite has no visible pixels: ${assetPath}`);

    const upperLimit = Math.min(
        info.height - 1,
        minY + Math.round((maxY - minY + 1) * UPPER_BODY_FRACTION),
    );
    let upperMinX = info.width;
    let upperMaxX = -1;
    for (let y = minY; y <= upperLimit; y += 1) {
        for (let x = minX; x <= maxX; x += 1) {
            const alpha = data[((y * info.width) + x) * info.channels + alphaIndex];
            if (alpha <= ALPHA_THRESHOLD) continue;
            upperMinX = Math.min(upperMinX, x);
            upperMaxX = Math.max(upperMaxX, x);
        }
    }
    const upperWidth = upperMaxX >= upperMinX ? upperMaxX - upperMinX + 1 : maxX - minX + 1;
    return {
        relativeUpperWidth: upperWidth / info.width,
        relativeTop: minY / info.height,
    };
}

function readJsonConstant(source, name) {
    const marker = `export const ${name} = `;
    const start = source.indexOf(marker);
    if (start < 0) throw new Error(`Missing ${name}.`);
    const valueStart = start + marker.length;
    const valueEnd = source.indexOf(' as const', valueStart);
    if (valueEnd < 0) throw new Error(`Could not parse ${name}.`);
    return JSON.parse(source.slice(valueStart, valueEnd));
}

function clamp(value, minimum, maximum) {
    return Math.min(maximum, Math.max(minimum, value));
}

function round(value) {
    return Math.round(value * 1000) / 1000;
}
