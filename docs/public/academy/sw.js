let audioCacheQueue = Promise.resolve();
let audioCacheGeneration = 0;
const queuedAudioPaths = new Set();

function cacheRequestedAudio(path, deliveredResponse) {
    if (queuedAudioPaths.has(path)) return audioCacheQueue;
    queuedAudioPaths.add(path);
    const generation = audioCacheGeneration;
    const completeDeliveredResponse = deliveredResponse.status === 200
        ? deliveredResponse.clone()
        : undefined;
    const queued = audioCacheQueue.catch(() => {}).then(async () => {
        if (generation !== audioCacheGeneration) return;
        const cache = await caches.open(AUDIO_CACHE);
        if (await cache.match(path, { ignoreVary: true })) return;
        try {
            const request = new Request(path, { credentials: 'include', cache: 'no-store' });
            const response = completeDeliveredResponse ?? await fetch(request);
            if (response.status !== 200 || !response.headers.get('content-type')?.startsWith('audio/')) return;
            if (generation !== audioCacheGeneration) return;
            await cache.put(request, response);
        } catch {
            // Demand-cached audio never blocks playback when auth, media, network, or quota is unavailable.
        }
    }).finally(() => {
        queuedAudioPaths.delete(path);
    });
    audioCacheQueue = queued;
    return queued;
}

function purgeAudioCache() {
    audioCacheGeneration += 1;
    queuedAudioPaths.clear();
    return caches.delete(AUDIO_CACHE);
}

async function cachedAudioResponse(response, rangeHeader) {
    const match = /^bytes=(\d*)-(\d*)$/.exec(rangeHeader?.trim() ?? '');
    if (!match || (match[1] === '' && match[2] === '')) return response;
    const body = await response.blob();
    let start;
    let end;
    if (match[1] === '') {
        const suffix = Math.min(Number(match[2]), body.size);
        if (suffix === 0) return new Response(null, { status: 416, headers: { 'content-range': `bytes */${body.size}` } });
        start = body.size - suffix;
        end = body.size - 1;
    } else {
        start = Number(match[1]);
        if (start >= body.size) return new Response(null, { status: 416, headers: { 'content-range': `bytes */${body.size}` } });
        end = match[2] === '' ? body.size - 1 : Math.min(Number(match[2]), body.size - 1);
        if (end < start) return new Response(null, { status: 416, headers: { 'content-range': `bytes */${body.size}` } });
    }
    const headers = new Headers(response.headers);
    headers.set('accept-ranges', 'bytes');
    headers.set('content-length', String(end - start + 1));
    headers.set('content-range', `bytes ${start}-${end}/${body.size}`);
    return new Response(body.slice(start, end + 1, body.type), { status: 206, headers });
}

self.addEventListener('install', event => {
    event.waitUntil(installOfflineShell());
});

async function installOfflineShell() {
    const cache = await caches.open(VERSION);
    await cache.addAll(CORE);
    const response = await cache.match(STORY_VOICE_CATALOG);
    if (!response) throw new Error('Story voice catalog was not cached.');
    const catalog = await response.json();
    if (catalog?.schema !== 'yomu-academy.story-voice-playback.v1' || !Array.isArray(catalog.entries)) {
        throw new Error('Story voice catalog is invalid.');
    }
    const storyVoicePaths = [...new Set(catalog.entries.map(entry => entry?.url))];
    if (storyVoicePaths.length === 0 || storyVoicePaths.some(path => (
        typeof path !== 'string' || !STORY_VOICE_ASSET.test(path) || path.split('/').includes('..')
    ))) throw new Error('Story voice catalog contains an invalid asset path.');
    await cache.addAll(storyVoicePaths);
    await self.skipWaiting();
}

self.addEventListener('activate', event => {
    event.waitUntil(
        caches.keys()
            .then(keys => Promise.all(keys.filter(key => (
                key.startsWith('yomu-academy-') && key !== VERSION && key !== AUDIO_CACHE
            )).map(key => caches.delete(key))))
            .then(() => self.clients.claim()),
    );
});

self.addEventListener('fetch', event => {
    const request = event.request;
    const url = new URL(request.url);
    if (request.method === 'POST' && url.origin === self.location.origin && url.pathname === '/academy/api/logout') {
        event.respondWith(fetch(request).then(response => {
            if (response.ok) event.waitUntil(purgeAudioCache());
            return response;
        }));
        return;
    }
    if (request.method === 'GET' && url.origin === self.location.origin && url.pathname === '/academy/api/session') {
        event.respondWith(fetch(request).then(response => {
            if (response.status === 401) event.waitUntil(purgeAudioCache());
            return response;
        }));
        return;
    }
    if (request.method !== 'GET') return;
    const isReaderRuntime = url.pathname === '/yomu.user.js'
        || url.pathname === '/yomu.css'
        || url.pathname === '/greasyfork/yomu-ui-copy.user.js'
        || url.pathname === '/greasyfork/yomu-settings-surface.user.js'
        || url.pathname === '/greasyfork/yomu-kanji-study.user.js'
        || url.pathname === '/greasyfork/yomu-anki.user.js'
        || url.pathname === '/greasyfork/yomu-bunpro.user.js';
    if (url.origin !== self.location.origin || (!url.pathname.startsWith('/academy/') && !isReaderRuntime)) return;
    if (url.pathname.startsWith('/academy/media/')) {
        if (!AUDIO_PRECACHE.includes(url.pathname)) return;
        event.respondWith(caches.open(AUDIO_CACHE).then(async cache => {
            const cached = await cache.match(url.pathname, { ignoreVary: true });
            if (cached) return cachedAudioResponse(cached, request.headers.get('range'));
            try {
                const response = await fetch(request);
                if (response.ok) event.waitUntil(cacheRequestedAudio(url.pathname, response));
                return response;
            } catch {
                return new Response(null, { status: 503 });
            }
        }));
        return;
    }
    // Authentication and byte-range semantics stay with the Worker/R2
    // boundary. Generic shell caching never persists protected media.
    if (url.pathname.startsWith('/academy/api/')) return;
    if (request.mode === 'navigate') {
        event.respondWith(fetch(request).then(response => {
            if (!response.ok) return response;
            const copy = response.clone();
            event.waitUntil(caches.open(VERSION).then(cache => cache.put('/academy/index.html', copy)));
            return response;
        }).catch(async () => await caches.match('/academy/index.html')
            ?? new Response('よむ Academy is not available offline yet.', { status: 503 })));
        return;
    }
    event.respondWith(caches.match(request).then(cached => cached ?? fetch(request).then(response => {
        if (!response.ok) return response;
        const copy = response.clone();
        event.waitUntil(caches.open(VERSION).then(cache => cache.put(request, copy)));
        return response;
    })));
});
