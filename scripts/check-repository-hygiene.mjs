#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const forbiddenRoots = [
    '.agents',
    '.claude',
    '.codex',
    '.cursor',
    '.idea',
    '.playwright-mcp',
    '.vscode',
    'artifacts',
    'cast-standardize',
    'qa-artifacts',
    'references',
    'references-academy',
    'release-worktrees',
    'screens',
    'tmp',
    'verify',
];

const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' })
    .split('\0')
    .filter(Boolean);
const violations = tracked.filter(file => forbiddenRoots.some(directory => file === directory || file.startsWith(`${directory}/`)));

if (violations.length > 0) {
    console.error('Repository-local research, generated evidence, or tool state is tracked:');
    for (const file of violations) console.error(`  ${file}`);
    console.error('Keep these files outside the product repository; the matching roots are ignored.');
    process.exit(1);
}

// A root blocklist alone did not stop 39 MB of QA screenshots from being committed
// under docs/academy/evidence/, because docs/ is a legitimate root. So authored
// docs get their own weight rule. docs/public/ is exempt: it is generated hosted
// output whose size is already governed by the artifact-drift gate and the
// content-addressed retention pruner.
const BINARY_EXTENSIONS = /\.(png|jpe?g|webp|gif|avif|bmp|tiff?|ico|mp4|webm|mov|mp3|wav|ogg|opus|m4a|pdf|zip|gz|woff2?|ttf|otf|eot|wasm|psd|ai|sketch)$/i;
// The one archive of binaries authored docs may keep: tests/academy assert the
// shipped runtime art is byte-identical to these recovered originals, so they are
// provenance for the product, not evidence of a QA run.
const BINARY_ALLOWLIST_PREFIX = 'docs/academy/recovery/recovered-assets/';
const BINARY_SIZE_LIMIT = 1024 * 1024;
const LARGE_FILE_LIMIT = 2 * 1024 * 1024;
// Text ledgers over the limit, each read by tests, each named so a new one has to
// be argued for rather than slipped in.
const LARGE_FILE_ALLOWLIST = new Map([
    ['docs/academy/recovery/ASSET-CARRYOVER.json', 'asset recovery ledger; asset-recovery-ledger.test.ts asserts byte equality with serializeLedger()'],
    ['docs/academy/audio/voice-production-manifest.json', 'learning-voice production manifest; learning-voice-provenance and playback tests read it'],
]);

const authoredDocs = tracked.filter(file => file.startsWith('docs/') && !file.startsWith('docs/public/'));
const weightViolations = [];
for (const file of authoredDocs) {
    const bytes = statSync(join(root, file)).size;
    const binary = BINARY_EXTENSIONS.test(file);
    if (binary && !file.startsWith(BINARY_ALLOWLIST_PREFIX)) {
        weightViolations.push(`${file} (${bytes} bytes) is a tracked binary outside ${BINARY_ALLOWLIST_PREFIX}`);
        continue;
    }
    if (binary && bytes > BINARY_SIZE_LIMIT) {
        weightViolations.push(`${file} (${bytes} bytes) is over the ${BINARY_SIZE_LIMIT}-byte limit for tracked docs binaries`);
        continue;
    }
    if (!binary && bytes > LARGE_FILE_LIMIT && !LARGE_FILE_ALLOWLIST.has(file)) {
        weightViolations.push(`${file} (${bytes} bytes) is over the ${LARGE_FILE_LIMIT}-byte limit and is not in LARGE_FILE_ALLOWLIST`);
    }
}

if (weightViolations.length > 0) {
    console.error('Authored docs/ carry weight that belongs outside the repository:');
    for (const violation of weightViolations) console.error(`  ${violation}`);
    console.error('Screenshots and captures are local-only (README repository layout). If a binary is genuinely');
    console.error(`product provenance, put it under ${BINARY_ALLOWLIST_PREFIX}; if a text ledger must be this large,`);
    console.error('add it to LARGE_FILE_ALLOWLIST in this file with the reason.');
    process.exit(1);
}

// The Academy hosted mirror is regenerated by scripts/sync-academy.cjs on every
// build:academy, and committing it cost 239 MB of byte-identical duplicates. Only
// the four files whose committed bytes a gate reads may be tracked.
const ACADEMY_MIRROR_TRACKED = ['app.js', 'index.html', 'style.css', 'sw.js']
    .map(name => `docs/public/academy/${name}`);
const academyMirror = tracked.filter(file => file.startsWith('docs/public/academy/'));
const unexpectedMirror = academyMirror.filter(file => !ACADEMY_MIRROR_TRACKED.includes(file));
if (unexpectedMirror.length > 0) {
    console.error(`The generated Academy mirror is tracked again (${unexpectedMirror.length} extra files):`);
    for (const file of unexpectedMirror.slice(0, 10)) console.error(`  ${file}`);
    if (unexpectedMirror.length > 10) console.error(`  ... and ${unexpectedMirror.length - 10} more`);
    console.error('public/academy/ is the source; npm run build:academy rebuilds the mirror. Only these may be tracked:');
    for (const file of ACADEMY_MIRROR_TRACKED) console.error(`  ${file}`);
    process.exit(1);
}

console.log(`Repository hygiene passed (${tracked.length} tracked files, no local-only roots, ${authoredDocs.length} authored docs within weight limits).`);
