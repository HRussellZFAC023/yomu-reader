import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chmodSync, existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { StageCache } from '../../scripts/lib/stage-cache.mjs';
test('writer hits restore passed bytes, remove extras and rebuild when immutable blobs are missing or writable', async t => {
    const root = mkdtempSync(join(tmpdir(), 'yomu-output-restore-'));
    t.after(() => rmSync(root, { recursive: true, force: true }));
    const cache = new StageCache(root, { directory: join(root, 'cache') });
    const stage = { name: 'build', key: 'key', outputs: ['dist/**'], restoreOutputs: true };
    let calls = 0;
    const build = () => { calls++; mkdirSync(join(root, 'dist'), { recursive: true }); writeFileSync(join(root, 'dist/app.js'), 'passed'); };
    await cache.run(stage, build);
    writeFileSync(join(root, 'dist/app.js'), 'corrupt');
    writeFileSync(join(root, 'dist/extra.js'), 'extra');
    assert.equal((await cache.run(stage, build)).cached, true);
    assert.equal(readFileSync(join(root, 'dist/app.js'), 'utf8'), 'passed');
    assert.equal(existsSync(join(root, 'dist/extra.js')), false);
    assert.equal(calls, 1);
    const marker = JSON.parse(readFileSync(cache.markerPath(stage.name, stage.key), 'utf8'));
    const blob = cache.outputStore.blob(marker.outputs['dist/app.js']);
    chmodSync(blob, 0o644);
    writeFileSync(blob, 'broken');
    assert.equal((await cache.run(stage, build)).cached, false);
    assert.equal(calls, 2);
    rmSync(blob);
    assert.equal((await cache.run(stage, build)).cached, false);
    assert.equal(calls, 3);
});
