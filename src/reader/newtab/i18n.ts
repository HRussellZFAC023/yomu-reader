const NEW_TAB_COPY_BY_LANGUAGE: Record<NewTabLanguage, Partial<Record<NewTabCopyKey, string>>> = {
    en: NEW_TAB_COPY.en,
    ja: { ...NEW_TAB_COPY.en, ...JA_NEW_TAB_COPY },
};

const NEW_TAB_COPY_KEYS = new Set<string>(Object.keys(NEW_TAB_COPY.en));

export function isNewTabCopyKey(key: string): key is NewTabCopyKey {
    return NEW_TAB_COPY_KEYS.has(key);
}

export function newTabText(language: InterfaceLanguage, key: NewTabCopyKey): string {
    return NEW_TAB_COPY_BY_LANGUAGE[resolveNewTabLanguage(language)][key] ?? NEW_TAB_COPY.en[key];
}

function resolveNewTabLanguage(language: InterfaceLanguage): NewTabLanguage {
    return language === 'ja' ? 'ja' : 'en';
}
