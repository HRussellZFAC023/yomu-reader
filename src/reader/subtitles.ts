function localizedSubtitleTrackLabel(track: SubtitleTrackOption, language: InterfaceLanguage): string {
    if (language !== 'ja') return track.label;
    if (track.label === 'YouTube subtitles') return uiText(language, 'youTubeSubtitles');
    return track.label.replace(/ · auto-generated$/u, ` · ${uiText(language, 'autoGeneratedSubtitle')}`);
}

function trackRoleText(isPrimary: boolean, isSecondary: boolean, language: InterfaceLanguage): string {
    return [
        isPrimary ? ` · ${uiText(language, 'primaryOverlay')}` : '',
        isSecondary ? ` · ${uiText(language, 'nativeOverlay')}` : '',
    ].join('');
}

function drawerMetaParts(
    mode: 'lines' | 'tracks',
    count: number,
    primary: string | undefined,
    secondary: string | undefined,
    language: InterfaceLanguage,
): string[] {
    return mode === 'tracks'
        ? drawerTrackMetaParts(count, primary, secondary, language)
        : drawerLineMetaParts(count, primary, secondary, language);
}

function drawerTrackMetaParts(count: number, primary: string | undefined, secondary: string | undefined, language: InterfaceLanguage): string[] {
    return [
        `${count} ${uiText(language, count === 1 ? 'subtitleOptionSingular' : 'subtitleOptionPlural')}`,
        primary ? `${uiText(language, 'primarySubtitles')}: ${primary}` : uiText(language, 'choosePrimarySubtitles'),
        secondary ? `${uiText(language, 'nativeSubtitles')}: ${secondary}` : '',
    ];
}

function drawerLineMetaParts(count: number, primary: string | undefined, secondary: string | undefined, language: InterfaceLanguage): string[] {
    return [
        primary || uiText(language, 'transcript'),
        `${count} ${uiText(language, count === 1 ? 'subtitleLineSingular' : 'subtitleLinePlural')}`,
        secondary ? `${uiText(language, 'nativeSubtitles')}: ${secondary}` : '',
    ];
}

function videoSummary(video: HTMLVideoElement): Record<string, unknown> {
    return {
        currentSrcHost: safeHost(video.currentSrc || video.src),
        width: video.videoWidth || video.clientWidth,
        height: video.videoHeight || video.clientHeight,
        textTracks: video.textTracks.length,
    };
}

function videoElementArea(video: HTMLVideoElement): number {
    const rect = video.getBoundingClientRect();
    return rect.width * rect.height;
}

function compareSubtitleVideoCandidates(a: HTMLVideoElement, b: HTMLVideoElement): number {
    return videoElementVisibleArea(b) - videoElementVisibleArea(a)
        || videoElementArea(b) - videoElementArea(a);
}

function videoElementVisibleArea(video: HTMLVideoElement): number {
    return rectViewportIntersectionArea(video.getBoundingClientRect());
}

function isSubtitleOverlayVideoVisible(rect: DOMRect): boolean {
    const visible = rectViewportIntersection(rect);
    if (visible.width < SUBTITLE_MIN_VISIBLE_VIDEO_WIDTH || visible.height < SUBTITLE_MIN_VISIBLE_VIDEO_HEIGHT) return false;
    const area = rectArea(rect);
    return area > 0 && rectArea(visible) / area >= SUBTITLE_MIN_VISIBLE_VIDEO_RATIO;
}

function rectViewportIntersectionArea(rect: DOMRect): number {
    return rectArea(rectViewportIntersection(rect));
}

function rectViewportIntersection(rect: DOMRect): DOMRect {
    const left = clampNumber(rect.left, 0, window.innerWidth);
    const top = clampNumber(rect.top, 0, window.innerHeight);
    const right = clampNumber(rect.right, left, window.innerWidth);
    const bottom = clampNumber(rect.bottom, top, window.innerHeight);
    return new DOMRect(left, top, Math.max(0, right - left), Math.max(0, bottom - top));
}

function rectArea(rect: DOMRect): number {
    return Math.max(0, rect.width) * Math.max(0, rect.height);
}

function safeHost(value: string): string {
    try {
        return new URL(value, location.href).host;
    } catch {
        return value ? 'inline-or-invalid' : '';
    }
}

function mutationInsideReaderRoot(mutation: MutationRecord): boolean {
    const nodes = [
        mutation.target,
        ...Array.from(mutation.addedNodes),
        ...Array.from(mutation.removedNodes),
    ];
    return nodes.every(node => {
        const element = node.nodeType === 1
            ? node as Element
            : node.parentElement;
        return Boolean(element?.closest?.('[data-jpdb-reader-root]'));
    });
}

function mutationCouldAffectVideoDiscovery(mutation: MutationRecord): boolean {
    const nodes = [
        ...Array.from(mutation.addedNodes),
        ...Array.from(mutation.removedNodes),
    ];
    return nodes.some(nodeContainsVideoElement);
}

function nodeContainsVideoElement(node: Node): boolean {
    if (node instanceof HTMLVideoElement) return true;
    return node instanceof Element && Boolean(node.querySelector('video'));
}
