function git(root, args, { allowFailure = false } = {}) {
    const result = spawnSync('git', ['-C', root, ...args], { encoding: 'utf8' });
    if (result.status !== 0 && !allowFailure) {
        throw new Error(`git -C ${root} ${args.join(' ')} failed: ${result.stderr.trim()}`);
    }
    return result.status === 0 ? result.stdout.trimEnd() : '';
}

function lines(value) {
    return value ? value.split(/\r?\n/u).filter(Boolean) : [];
}

function statusEntry(line) {
    return { code: line.slice(0, 2), path: line.slice(3) };
}

function diffEntry(line) {
    const [status, ...paths] = line.split('\t');
    return { status, paths };
}

function academyRelevant(entry) {
    const candidate = 'path' in entry ? entry.path : entry.paths.join(' ');
    return /(^|\/)(academy|yomu-academy)(\/|\.|$)|academy-/u.test(candidate);
}

function mergeBase(root) {
    return git(root, ['merge-base', 'HEAD', 'origin/main'], { allowFailure: true })
        || git(root, ['rev-parse', 'HEAD^'], { allowFailure: true })
        || git(root, ['rev-parse', 'HEAD']);
}

function snapshot(source) {
    const head = git(source.root, ['rev-parse', 'HEAD']);
    const branch = git(source.root, ['branch', '--show-current'], { allowFailure: true });
    const baseRef = source.baseRef && git(source.root, ['cat-file', '-e', `${source.baseRef}^{commit}`], { allowFailure: true }) === ''
        ? source.baseRef
        : mergeBase(source.root);
    const status = lines(git(source.root, ['status', '--porcelain=v1', '-uall'])).map(statusEntry);
    const committed = lines(git(source.root, ['diff', '--name-status', `${baseRef}..${head}`])).map(diffEntry);
    const working = lines(git(source.root, ['diff', '--name-status'])).map(diffEntry);
    const commits = lines(git(source.root, ['log', '--format=%H%x09%s', `${baseRef}..${head}`])).map(line => {
        const [commit, ...subject] = line.split('\t');
        return { commit, subject: subject.join('\t') };
    });
    return {
        id: source.id,
        kind: source.kind,
        root: source.root,
        readOnly: true,
        head,
        branch: branch || null,
        baseRef,
        commits,
        committedDiff: committed,
        workingDiff: working,
        status,
        counts: {
            commits: commits.length,
            committedPaths: committed.length,
            workingPaths: working.length,
            trackedStatusPaths: status.filter(entry => entry.code !== '??').length,
            untrackedStatusPaths: status.filter(entry => entry.code === '??').length,
            academyRelevantPaths: [
                ...committed.filter(academyRelevant),
                ...status.filter(academyRelevant),
            ].length,
        },
    };
}

function markdown(inventory) {
    const rows = inventory.sources.map(source => {
        const shortHead = source.head.slice(0, 10);
        const branch = source.branch ?? '(detached)';
        const counts = source.counts;
        return `| ${source.id} | \`${shortHead}\` | ${branch} | ${counts.commits} | ${counts.committedPaths} | ${counts.trackedStatusPaths} | ${counts.untrackedStatusPaths} | ${counts.academyRelevantPaths} |`;
    });
    return `# Stage 0 donor and worktree inventory

Generated by \`node scripts/academy-baseline-inventory.mjs\` at ${inventory.generatedAt}. Every listed source is read-only evidence; only the canonical repository may be edited.

| Source | HEAD | Branch | Commits from base | Committed paths | Dirty tracked | Dirty untracked | Academy-relevant records |
| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |
${rows.join('\n')}

The lossless path/status/commit inventory is in [inventory.json](inventory.json). Salvage decisions live in [../../SALVAGE-LEDGER.md](../../SALVAGE-LEDGER.md); a path appearing here is not approval to port it.
`;
}

const canonical = {
    root: REPO_ROOT,
    head: git(REPO_ROOT, ['rev-parse', 'HEAD']),
    branch: git(REPO_ROOT, ['branch', '--show-current']),
    originMain: git(REPO_ROOT, ['rev-parse', 'origin/main']),
};
