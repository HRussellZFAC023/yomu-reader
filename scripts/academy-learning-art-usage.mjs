#!/usr/bin/env node

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '..');
const usageFiles = [
    path.join(repoRoot, 'public/academy/art/ASSET-USAGE.json'),
    path.join(repoRoot, 'docs/public/academy/art/ASSET-USAGE.json'),
];
const runtimeManifestFile = path.join(
    repoRoot,
    'src/academy/domain/learning-art-manifest.ts',
);
const families = [
    {
        id: 'lesson-zero-hiragana-anchor-family-v001',
        assetIdPrefix: 'learning.hiragana-anchor',
        directory: 'lesson-zero/hiragana-anchors',
        runtimeHome: ['lesson-zero:kana-practice', 'lesson-zero:hiragana-visual-anchor'],
        status: 'complete gojuon visual-anchor family; learner-facing and hash-locked',
    },
    {
        id: 'academy-vocabulary-pictograph-family-v001',
        assetIdPrefix: 'learning.vocabulary-pictograph',
        directory: 'vocabulary-pictographs',
        runtimeHome: ['lesson:l1-l01:vocabulary-pictographs', 'lesson-zero:sentence-frames'],
        status: 'lesson vocabulary visual-anchor family; learner-facing and hash-locked',
    },
];

const usage = JSON.parse(fs.readFileSync(usageFiles[0], 'utf8'));
const familyPrefixes = families.map(family => `/academy/art/${family.directory}/`);
usage.assets = usage.assets.filter(asset =>
    !families.some(family => asset.id === family.id)
    && !(asset.deliveries ?? []).some(delivery =>
        familyPrefixes.some(prefix => delivery.path.startsWith(prefix))),
);

for (const family of families) {
    const publicDirectory = path.join(repoRoot, 'public/academy/art', family.directory);
    const docsDirectory = path.join(repoRoot, 'docs/public/academy/art', family.directory);
    const files = fs.readdirSync(publicDirectory)
        .filter(file => file.endsWith('.webp'))
        .sort();
    if (files.length === 0) throw new Error(`${family.id} has no WebP deliveries.`);

    const deliveries = files.map(file => {
        const publicFile = path.join(publicDirectory, file);
        const docsFile = path.join(docsDirectory, file);
        if (!fs.existsSync(docsFile)) throw new Error(`${family.id} is missing docs mirror ${file}.`);
        const digest = sha256(fs.readFileSync(publicFile));
        if (sha256(fs.readFileSync(docsFile)) !== digest) {
            throw new Error(`${family.id} mirror drift: ${file}.`);
        }
        return {
            path: `/academy/art/${family.directory}/${file}`,
            sha256: digest,
        };
    });

    usage.assets.push({
        id: family.id,
        source: `repo-authored:public/academy/art/${family.directory}`,
        provenance: 'regenerated-house-style',
        verdict: 'approved-runtime',
        runtimeHome: family.runtimeHome,
        reviewHome: ['learning-art-inventory'],
        usage: {
            runtime: family.runtimeHome,
            review: ['learning-art-inventory'],
        },
        orphan: 'active-runtime',
        deliveries,
        status: family.status,
    });
}

const runtimeAssets = usage.assets.filter(
    asset =>
        asset.verdict?.startsWith('approved-runtime')
        || asset.verdict === 'review-candidate/runtime-preview',
);
const visualRuntimeAssets = runtimeAssets.filter(asset =>
    (asset.deliveries ?? []).some(delivery => !delivery.path.endsWith('.json')),
);
const visualRuntimeFiles = runtimeAssets
    .flatMap(asset => asset.deliveries ?? [])
    .filter(delivery => !delivery.path.endsWith('.json'));
usage.counts.runtimeAssetHomes = visualRuntimeAssets.length;
usage.counts.runtimeFiles = visualRuntimeFiles.length;

const serialized = `${JSON.stringify(usage, null, 2)}\n`;
for (const usageFile of usageFiles) fs.writeFileSync(usageFile, serialized);

const learningRuntimeAssets = Object.fromEntries(families.flatMap(family => {
    const files = fs.readdirSync(path.join(repoRoot, 'public/academy/art', family.directory))
        .filter(file => file.endsWith('.webp'))
        .sort();
    return files.map(file => {
        const basename = file.slice(0, -'.webp'.length);
        const slug = family.assetIdPrefix === 'learning.hiragana-anchor'
            ? basename.replace(/^hira-/, '')
            : basename;
        return [
            `${family.assetIdPrefix}.${slug}`,
            {
                kind: 'learning-visual',
                status: 'approved',
                runtimeHomes: family.runtimeHome,
                provenance: 'regenerated-house-style',
                files: {
                    default: `/academy/art/${family.directory}/${file}`,
                },
            },
        ];
    });
}));
fs.writeFileSync(
    runtimeManifestFile,
    `// Generated by scripts/academy-learning-art-usage.mjs. Do not edit by hand.\n`
        + `export const ACADEMY_LEARNING_ART_RUNTIME_ASSETS = ${JSON.stringify(learningRuntimeAssets, null, 4)} as const;\n`,
);

console.log(
    `Registered ${families.length} learning-art families with`
    + ` ${families.reduce((total, family) => total + fs.readdirSync(
        path.join(repoRoot, 'public/academy/art', family.directory),
    ).filter(file => file.endsWith('.webp')).length, 0)} hashed deliveries.`,
);

function sha256(bytes) {
    return crypto.createHash('sha256').update(bytes).digest('hex');
}
