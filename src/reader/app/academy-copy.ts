export function academyText(language: AcademyLanguage, key: AcademyCopyKey): string {
    return language === 'ja' ? JA[key] : EN[key];
}

export function academyCopyHasMissingJapanese(): boolean {
    return (Object.keys(EN) as AcademyCopyKey[]).some(key => !JA[key].trim() || JA[key] === '未翻訳');
}
